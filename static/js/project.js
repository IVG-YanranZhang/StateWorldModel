"use strict";
(() => {
  const $ = (selector, scope = document) => scope.querySelector(selector);
  const $$ = (selector, scope = document) => [
    ...scope.querySelectorAll(selector),
  ];
  const escape = (value) =>
    String(value ?? "").replace(
      /[&<>"']/g,
      (char) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&#39;",
        })[char],
    );
  const title = (value) =>
    String(value).replace(/\b\w/g, (char) => char.toUpperCase());
  const worlds = [
    {
      id: "duel_moon_dragon",
      name: "Moon Dragon",
      description:
        "A multi-turn boss duel with counter cycles and a charged eclipse release. Each action is settled by rules before rendering.",
    },
    {
      id: "romance",
      name: "Quiet Hours",
      description:
        "A dating narrative driven by free-form dialogue. The runtime tracks affection and scene progress, settling each interaction before the frozen model renders it.",
    },
    {
      id: "openworld",
      name: "The Wanted",
      description:
        "Town exploration with a main quest and free interaction. Talk, gather, and advance the story while the runtime carries an explicit world ledger across turns.",
    },
  ];
  const hero = $("#hero-video");
  const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)");
  let heroVisible = true;
  let currentWorld = worlds[0];
  let heroManualPause = false;
  const autoHero = () =>
    innerWidth >= 768 &&
    !reduceMotion.matches &&
    !navigator.connection?.saveData;
  function reflectHero() {
    $("#hero-play-label").textContent = hero.paused
      ? "Play scene"
      : "Pause scene";
    $("#hero-play-icon").textContent = hero.paused ? "▷" : "Ⅱ";
    $("#hero-play").setAttribute(
      "aria-label",
      hero.paused
        ? "Play the generated world video"
        : "Pause the generated world video",
    );
  }
  hero.addEventListener("play", reflectHero);
  hero.addEventListener("pause", reflectHero);
  $("#hero-play").addEventListener("click", async () => {
    if (hero.paused) {
      heroManualPause = false;
      try {
        await hero.play();
      } catch {
        reflectHero();
      }
    } else {
      heroManualPause = true;
      hero.pause();
    }
  });
  $$("[data-world]").forEach((button) =>
    button.addEventListener("click", async () => {
      const world = worlds[Number(button.dataset.world)];
      currentWorld = world;
      const continuePlaying = !hero.paused;
      hero.pause();
      hero.poster = `static/images/games/${world.id}.webp`;
      $("source", hero).src = `static/videos/worlds/${world.id}-preview.mp4`;
      hero.setAttribute(
        "aria-label",
        `${world.name}, generated by Stateful Harness`,
      );
      $("#hero-video-link").href = `static/videos/${world.id}.mp4`;
      $("#hero-video-link").setAttribute(
        "aria-label",
        `Open the ${world.name} highlight video`,
      );
      $("#world-description").textContent = world.description;
      $$("[data-world]").forEach((item) => {
        const active = item === button;
        item.classList.toggle("active", active);
        item.setAttribute("aria-pressed", String(active));
      });
      hero.load();
      if (continuePlaying)
        try {
          await hero.play();
        } catch {
          reflectHero();
        }
    }),
  );
  const episodeDialog = $("#episode-dialog");
  const episodeVideo = $("#episode-video");
  $("#hero-video-link").addEventListener("click", (event) => {
    event.preventDefault();
    hero.pause();
    $("#episode-dialog-title").textContent = currentWorld.name;
    episodeVideo.src = `static/videos/${currentWorld.id}.mp4`;
    episodeVideo.poster = `static/images/games/${currentWorld.id}.webp`;
    episodeVideo.setAttribute(
      "aria-label",
      `${currentWorld.name}, generated episode replay`,
    );
    episodeDialog.showModal();
    document.body.classList.add("dialog-open");
    episodeVideo.play().catch(() => {});
  });
  $("#episode-close").addEventListener("click", () => episodeDialog.close());
  episodeDialog.addEventListener("close", () => {
    episodeVideo.pause();
    document.body.classList.remove("dialog-open");
    if (heroVisible && autoHero() && !heroManualPause)
      hero.play().catch(reflectHero);
  });
  episodeDialog.addEventListener("click", (event) => {
    if (event.target === episodeDialog) {
      const r = episodeDialog.getBoundingClientRect();
      if (
        event.clientX < r.left ||
        event.clientX > r.right ||
        event.clientY < r.top ||
        event.clientY > r.bottom
      )
        episodeDialog.close();
    }
  });
  new IntersectionObserver(
    (entries) => {
      heroVisible = entries[0].isIntersecting;
      if (!heroVisible) hero.pause();
      else if (autoHero() && !heroManualPause && !document.hidden)
        hero.play().catch(reflectHero);
    },
    { threshold: 0.18 },
  ).observe($(".cinematic"));
  const header = $(".site-header");
  let ticking = false;
  const updateHeader = () => {
    const overHero = scrollY < $(".cinematic").offsetHeight - 76;
    header.classList.toggle("over-hero", overHero);
    let active = overHero ? "worlds" : "";
    for (const id of ["method", "results", "benchmark"])
      if ($("#" + id).getBoundingClientRect().top <= 150) active = id;
    if ($("#resources").getBoundingClientRect().top <= 150) active = "";
    $$(".nav-links a").forEach((link) => {
      const current = link.getAttribute("href") === "#" + active;
      link.classList.toggle("current", current);
      if (current) link.setAttribute("aria-current", "location");
      else link.removeAttribute("aria-current");
    });
    ticking = false;
  };
  addEventListener(
    "scroll",
    () => {
      if (!ticking) {
        ticking = true;
        requestAnimationFrame(updateHeader);
      }
    },
    { passive: true },
  );
  addEventListener("resize", updateHeader, { passive: true });
  updateHeader();

  function setRuntimeTwin(side) {
    const index = side === "A" ? 0 : 1;
    $("#runtime-ledger").textContent =
      `element_mode = ${index === 0 ? "RED_FLAME" : "BLUE_FLAME"}`;
    $("#runtime-settled").textContent =
      index === 0 ? "orb.flame = 'red'" : "orb.flame = 'blue'";
    $("#runtime-outcome").textContent =
      index === 0 ? "Red flames" : "Blue flames";
    $("#runtime-output").src =
      $("#runtime-demo").dataset[index === 0 ? "posterA" : "posterB"];
    $("#runtime-output").alt =
      `Recorded B01-${side} harness final frame: ${index === 0 ? "red" : "blue"} flames`;
    $("#runtime-recording-label").textContent =
      `Recorded B01-${side} / MiniMax-H3`;
    $("#runtime-demo").dataset.element = index === 0 ? "red" : "blue";
    $$("[data-runtime-twin]").forEach((button) => {
      const active = button.dataset.runtimeTwin === side;
      button.classList.toggle("active", active);
      button.setAttribute("aria-pressed", String(active));
    });
  }
  $$("[data-runtime-twin]").forEach((button) =>
    button.addEventListener("click", () =>
      setRuntimeTwin(button.dataset.runtimeTwin),
    ),
  );
  setRuntimeTwin("A");
  let pauseBench = () => {};
  function initializeBenchmark() {
    const samples = window.SWM_SAMPLES || [];
    const models = window.SWM_MODELS || [];
    const detail = $("#sample-detail");
    const select = $("#sample-select");
    const themes = $("#theme-filter");
    const gallery = $("#sample-gallery");
    const query = new URLSearchParams(location.search);
    let currentCase = samples.some((sample) => sample.id === query.get("case"))
      ? query.get("case")
      : samples[0]?.id || "B01";
    let baseline = models.some(
      (model) => model.key === query.get("model") && model.key !== "ours",
    )
      ? query.get("model")
      : "minimax";
    let probe = query.get("probe") === "ending" ? "ending" : "rule";
    let playbackGeneration = 0;
    let playingTogether = false;
    let comparisonObserver;
    pauseBench = () => {
      playbackGeneration++;
      playingTogether = false;
      $$("video", detail).forEach((clip) => clip.pause());
      const button = $("#bench-play", detail);
      if (button) {
        button.disabled = false;
        button.textContent = "Play comparison";
      }
    };
    function saveSelection() {
      const url = new URL(location.href);
      url.searchParams.set("case", currentCase);
      url.searchParams.set("model", baseline);
      url.searchParams.set("probe", probe);
      url.hash = "benchmark";
      history.replaceState(null, "", url);
    }
    function videoCard(record, modelName, side, isOurs) {
      if (!record)
        return `<article class="compare-player"><p class="recording-error">This archived recording is unavailable.</p></article>`;
      const strict = record.judge?.strictOk;
      const badge =
        strict === undefined
          ? ""
          : `<span class="judge-badge ${strict ? "pass" : "fail"}" title="Recorded VLM strict decision">${strict ? "✓" : "×"} VLM ${strict ? "pass" : "fail"}</span>`;
      return `<article class="compare-player ${isOurs ? "our-player" : ""}"><div class="player-heading"><span><b>${escape(modelName)}</b><small>Twin ${side} · ${isOurs ? "Text + first-frame reference" : probe === "rule" ? "Rule-only probe" : "Rule+end probe"}</small></span>${badge}</div><video controls playsinline preload="none" poster="${escape(record.poster)}" aria-label="${escape(modelName)}, ${escape(currentCase)}, twin ${side}"><source src="${escape(record.src)}" type="video/mp4"></video><div class="player-footer"><span>${record.duration.toFixed(1)} s · Original generated recording</span><a href="${escape(record.src)}" target="_blank" rel="noopener" aria-label="Open ${escape(modelName)} twin ${side} video">Open clip ↗</a></div></article>`;
    }
    function renderPlayers() {
      pauseBench();
      const sample = samples.find((item) => item.id === currentCase);
      const model = models.find((item) => item.key === baseline);
      if (!sample || !model) return;
      const ours = sample.recordings?.ours?.harness || {};
      const theirs = sample.recordings?.[baseline]?.[probe] || {};
      const host = $("#comparison-players", detail);
      host.innerHTML = ["A", "B"]
        .map(
          (side, index) =>
            `<div class="twin-row-title"><span class="twin-chip ${side.toLowerCase()}">Twin ${side}</span><p><span>Required ending</span> ${escape(sample.endings[index])}.</p></div><div class="paired-video-row">${videoCard(ours[side], "Stateful Harness", side, true)}${videoCard(theirs[side], model.name, side, false)}</div>`,
        )
        .join("");
      const evidence = ["A", "B"]
        .map((side) =>
          [
            ...[
              [ours[side], "Stateful Harness"],
              [theirs[side], model.name],
            ],
          ]
            .map(([record, name]) =>
              record?.judge
                ? `<article><p class="evidence-title">${escape(name)} / Twin ${side}</p><p>${escape(record.judge.evidence)}</p><small>Required ending: ${record.judge.outcomeOk ? "yes" : "no"} · Forbidden ending absent: ${record.judge.counterOk ? "yes" : "no"}</small></article>`
                : "",
            )
            .join(""),
        )
        .join("");
      $("#judge-evidence", detail).innerHTML = evidence;
      $("#selection-status").textContent =
        `${sample.id}, ${sample.name}. Comparing Stateful Harness with ${model.name}, ${probe === "rule" ? "rule-only" : "rule plus ending"} instructions. Four recordings available.`;
      $("#comparison-caption", detail).textContent =
        `${sample.id} · ${model.name} under the ${probe === "rule" ? "Rule-only" : "Rule+end"} probe. Our column uses the full harness with frozen MiniMax-H3.`;
      const playButton = $("#bench-play", detail);
      playButton.disabled = false;
      playButton.textContent = "Play comparison";
      $("#comparison-status", detail).textContent =
        "Posters show actual final frames. Use the video controls to inspect each complete clip.";
      $$("video", host).forEach((clip) => {
        clip.addEventListener("error", () => {
          if (!clip.isConnected) return;
          clip.closest("article").classList.add("media-failed");
          $("#comparison-status", detail).textContent =
            "A recording could not load. Use “Open clip” to view the original file.";
        });
        clip.addEventListener("ended", () => {
          if ($$("video", host).every((item) => item.ended || item.paused)) {
            playingTogether = false;
            playButton.textContent = "Replay comparison";
          }
        });
      });
    }
    async function playComparison() {
      const button = $("#bench-play", detail);
      const clips = $$("video", $("#comparison-players", detail));
      if (playingTogether) {
        pauseBench();
        button.textContent = "Play comparison";
        return;
      }
      const generation = ++playbackGeneration;
      button.disabled = true;
      button.textContent = "Loading recordings…";
      hero.pause();
      const ready = clips.map((clip) =>
        clip.readyState >= 1
          ? Promise.resolve()
          : new Promise((resolve, reject) => {
              const timeout = setTimeout(() => {
                cleanup();
                reject(new Error("timeout"));
              }, 18000);
              const cleanup = () => {
                clearTimeout(timeout);
                clip.removeEventListener("loadedmetadata", done);
                clip.removeEventListener("error", failed);
              };
              const done = () => {
                cleanup();
                resolve();
              };
              const failed = () => {
                cleanup();
                reject(new Error("media"));
              };
              clip.addEventListener("loadedmetadata", done, { once: true });
              clip.addEventListener("error", failed, { once: true });
              clip.load();
            }),
      );
      const loaded = await Promise.allSettled(ready);
      if (generation !== playbackGeneration) return;
      const available = clips.filter(
        (_, index) => loaded[index].status === "fulfilled",
      );
      available.forEach((clip) => {
        clip.currentTime = 0;
      });
      const started = await Promise.allSettled(
        available.map((clip) => clip.play()),
      );
      if (generation !== playbackGeneration) {
        available.forEach((clip) => clip.pause());
        return;
      }
      playingTogether = started.some((result) => result.status === "fulfilled");
      button.disabled = false;
      button.textContent = playingTogether
        ? "Pause comparison"
        : "Play comparison";
      $("#comparison-status", detail).textContent =
        loaded.some((result) => result.status === "rejected") ||
        started.some((result) => result.status === "rejected")
          ? "Some recordings could not start. Individual video controls remain available."
          : "Clips start together; each preserves its original duration.";
    }
    function renderSample(id, share = false) {
      const sample = samples.find((item) => item.id === id);
      if (!sample) return;
      pauseBench();
      currentCase = id;
      select.value = id;
      const twins = sample.values
        .map(
          (value, index) =>
            `<div class="twin ${index ? "b" : "a"}"><div class="twin-label"><span>TWIN ${index ? "B" : "A"}</span></div><code>${escape(sample.variable)} = ${escape(value)}</code><p><strong>Required</strong>${escape(sample.endings[index])}.</p><p class="forbidden"><strong>Must not occur</strong>${escape(sample.forbidden[index])}.</p></div>`,
        )
        .join("");
      const modelOptions = models
        .filter((model) => model.key !== "ours")
        .map(
          (model) =>
            `<option value="${escape(model.key)}" ${model.key === baseline ? "selected" : ""}>${escape(model.name)}</option>`,
        )
        .join("");
      detail.innerHTML = `<article class="sample-grid"><div class="sample-visual"><div class="frame-label"><span>${escape(sample.id)} / ${escape(title(sample.theme))}</span><span>Identical first frame</span></div><img src="${escape(sample.image)}" alt="${escape(sample.name)}: the shared first frame for both twins" width="960" height="540" loading="lazy"><div class="action"><small>Same action in both worlds</small><p>${escape(sample.action)}</p></div></div><div class="sample-state"><p class="eyebrow">${escape(sample.name)}</p><h3>Hidden state changes the ending.</h3><div class="twin-list">${twins}</div><details class="sample-program"><summary>Shared rule & executable transition <span aria-hidden="true">+</span></summary><p>${escape(sample.rule)}</p><pre><code>if ${escape(sample.program.precondition)}:\n    ${escape(sample.program.effect)}\nelse:\n    ${escape(sample.program.else_effect)}</code></pre></details></div></article>
    ${sample.failureCase ? '<p class="failure-case-note"><b>A rendering failure.</b> This example includes a missed required ending from our harness. Executing a valid transition does not guarantee that the video model depicts it faithfully.</p>' : ""}
    <div class="comparison-workbench"><div class="workbench-top"><div><p class="eyebrow">Actual model recordings</p><h3>Two hidden states. Four clips.</h3></div><div class="workbench-controls"><label for="baseline-select">Compare against<select id="baseline-select">${modelOptions}</select></label><div class="probe-control"><span>Baseline probe</span><div role="group" aria-label="Baseline instruction condition"><button data-probe="rule" aria-pressed="${probe === "rule"}" class="${probe === "rule" ? "active" : ""}">Rule-only</button><button data-probe="ending" aria-pressed="${probe === "ending"}" class="${probe === "ending" ? "active" : ""}">Rule + end</button></div></div></div></div><div class="workbench-actions"><p id="comparison-caption"></p><button class="small-button" id="bench-play">Play comparison</button></div><div id="comparison-players"></div><p id="comparison-status" class="fine-print" role="status">Posters show actual final frames. Use the video controls to inspect each complete clip.</p><details class="recorded-judgments"><summary>Recorded VLM judgments & evidence <span aria-hidden="true">+</span></summary><div id="judge-evidence"></div><p class="fine-print">Labels are the archived automatic judgments for these recordings. The ten examples are curated illustrations; the main table reports the full submission benchmark, not this showcase subset.</p></details></div>`;
      gallery.querySelectorAll("button").forEach((button) => {
        const active = button.dataset.sample === id;
        button.classList.toggle("active", active);
        button.setAttribute("aria-pressed", String(active));
      });
      $("#baseline-select", detail).addEventListener("change", (event) => {
        baseline = event.target.value;
        renderPlayers();
        saveSelection();
      });
      $$("[data-probe]", detail).forEach((button) =>
        button.addEventListener("click", () => {
          probe = button.dataset.probe;
          $$("[data-probe]", detail).forEach((item) => {
            const active = item === button;
            item.classList.toggle("active", active);
            item.setAttribute("aria-pressed", String(active));
          });
          renderPlayers();
          saveSelection();
        }),
      );
      $("#bench-play", detail).addEventListener("click", playComparison);
      renderPlayers();
      comparisonObserver?.disconnect();
      comparisonObserver = new IntersectionObserver(
        (entries) => {
          if (!entries[0].isIntersecting) pauseBench();
        },
        { rootMargin: "200px 0px" },
      );
      comparisonObserver.observe($(".comparison-workbench", detail));
      if (share) saveSelection();
    }
    function populate() {
      const theme = themes.value;
      const filtered = samples.filter(
        (sample) => theme === "all" || sample.theme === theme,
      );
      select.replaceChildren(
        ...filtered.map(
          (sample) =>
            new Option(
              `${sample.id} · ${sample.name || title(sample.theme)}`,
              sample.id,
            ),
        ),
      );
      $("#sample-count").textContent =
        theme === "all"
          ? `${samples.length} curated pairs · 50 in the full benchmark`
          : `${filtered.length} ${filtered.length === 1 ? "example" : "examples"} · ${title(theme)}`;
      gallery.innerHTML = filtered
        .map(
          (sample) =>
            `<button class="sample-thumb" data-sample="${escape(sample.id)}" aria-pressed="false"><img src="${escape(sample.image)}" alt="" width="160" height="90" loading="lazy"><span>${escape(sample.id)} / ${escape(sample.name || sample.theme)}</span></button>`,
        )
        .join("");
      $$("button", gallery).forEach((button) =>
        button.addEventListener("click", () =>
          renderSample(button.dataset.sample, true),
        ),
      );
      renderSample(
        filtered.some((sample) => sample.id === currentCase)
          ? currentCase
          : filtered[0]?.id,
      );
    }
    [...new Set(samples.map((sample) => sample.theme))]
      .sort()
      .forEach((theme) => themes.add(new Option(title(theme), theme)));
    select.addEventListener("change", () => renderSample(select.value, true));
    themes.addEventListener("change", () => {
      populate();
      saveSelection();
    });
    if (models.length) populate();
  }

  let benchmarkLoading = false;
  let benchmarkReady = false;
  const benchmarkStatus = $("#sample-count");
  const loadBenchmark = () => {
    if (benchmarkLoading || benchmarkReady) return;
    benchmarkLoading = true;
    $("#sample-select").disabled = true;
    $("#theme-filter").disabled = true;
    $("#benchmark").setAttribute("aria-busy", "true");
    benchmarkStatus.textContent = "Loading benchmark examples…";
    const script = document.createElement("script");
    script.src = "static/data/benchmark.js";
    script.onload = () => {
      benchmarkLoading = false;
      benchmarkReady = true;
      initializeBenchmark();
      $("#sample-select").disabled = false;
      $("#theme-filter").disabled = false;
      $("#benchmark").removeAttribute("aria-busy");
      $("#benchmark-retry")?.remove();
    };
    script.onerror = () => {
      benchmarkLoading = false;
      script.remove();
      $("#benchmark").removeAttribute("aria-busy");
      benchmarkStatus.textContent = "Examples could not load.";
      if (!$("#benchmark-retry")) {
        const retry = document.createElement("button");
        retry.id = "benchmark-retry";
        retry.className = "small-button";
        retry.textContent = "Retry loading";
        retry.addEventListener("click", loadBenchmark);
        benchmarkStatus.after(retry);
      }
    };
    document.head.append(script);
  };
  const benchmarkObserver = new IntersectionObserver(
    (entries) => {
      if (entries.some((entry) => entry.isIntersecting)) {
        benchmarkObserver.disconnect();
        loadBenchmark();
      }
    },
    { rootMargin: "1000px 0px" },
  );
  benchmarkObserver.observe($("#benchmark"));
  $$(".nav-links a, .hero-actions a, .resource-link")
    .filter((link) => link.getAttribute("href") === "#benchmark")
    .forEach((link) => link.addEventListener("click", loadBenchmark));
  if (
    location.hash === "#benchmark" ||
    new URLSearchParams(location.search).has("case")
  )
    loadBenchmark();
  reduceMotion.addEventListener("change", () => {
    if (reduceMotion.matches) {
      hero.pause();
      pauseBench();
    } else if (
      heroVisible &&
      autoHero() &&
      !heroManualPause &&
      !document.hidden
    )
      hero.play().catch(reflectHero);
  });
  matchMedia("(min-width: 768px)").addEventListener("change", (event) => {
    if (!event.matches) hero.pause();
    else if (heroVisible && autoHero() && !heroManualPause && !document.hidden)
      hero.play().catch(reflectHero);
  });
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      hero.pause();
      episodeVideo.pause();
      pauseBench();
      const button = $("#bench-play");
      if (button) {
        button.disabled = false;
        button.textContent = "Play comparison";
      }
    } else if (heroVisible && autoHero() && !heroManualPause)
      hero.play().catch(reflectHero);
  });
  $("#copy-citation").addEventListener("click", async () => {
    const text = $("#citation-text").textContent;
    const status = $("#copy-status");
    try {
      if (!navigator.clipboard?.writeText) throw new Error("clipboard");
      await navigator.clipboard.writeText(text);
      status.textContent = "BibTeX copied.";
    } catch {
      const selection = getSelection();
      const range = document.createRange();
      range.selectNodeContents($("#citation-text"));
      selection.removeAllRanges();
      selection.addRange(range);
      status.textContent = "Citation selected. Press Ctrl+C or ⌘C to copy.";
    }
  });
})();
